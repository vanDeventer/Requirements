// Builds an editing form from the element's field descriptions and keeps it
// in step with the JSON text area: editing either updates the other. The
// form posts the JSON, so the server checks it exactly as before. Without
// JavaScript, the JSON editor works on its own.
(() => {
	"use strict";
	const dataEl = document.getElementById("form-data");
	const ta = document.getElementById("json");
	const root = document.getElementById("form");
	const status = document.getElementById("json-status");
	if (!dataEl || !ta || !root) return;
	document.documentElement.classList.add("js");

	const D = JSON.parse(dataEl.textContent);
	// Fields most people rarely need go into a collapsed section.
	const LATER = ["description", "owner", "version", "rationale", "provenance"];
	const SINGULAR = { criteria: "criterion" };
	const one = (field) => SINGULAR[field] || field.replace(/s$/, "");
	let obj = parse(ta.value) || {};

	function parse(text) {
		try {
			const v = JSON.parse(text);
			return v && typeof v === "object" && !Array.isArray(v) ? v : null;
		} catch {
			return null;
		}
	}

	function h(tag, attrs, ...kids) {
		const e = document.createElement(tag);
		for (const [k, v] of Object.entries(attrs || {})) {
			if (k === "class") e.className = v;
			else if (k.startsWith("on")) e.addEventListener(k.slice(2), v);
			else if (v === true) e.setAttribute(k, "");
			else if (v !== false && v != null) e.setAttribute(k, v);
		}
		for (const kid of kids.flat()) {
			if (kid != null) e.append(kid);
		}
		return e;
	}

	const LABELS = { id: "ID", asil: "ASIL", cal: "CAL", externalID: "External ID", externalTool: "External tool", atVersion: "At version", approvedOn: "Approved on", approvedBy: "Approved by", generatedBy: "Generated by" };
	// A safety or security block belongs only to a requirement with that concern.
	const CONCERN_GROUPS = ["safety", "security"];

	function title(field) {
		if (LABELS[field]) return LABELS[field];
		const words = field.replace(/([a-z])([A-Z])/g, "$1 $2").toLowerCase();
		return words.charAt(0).toUpperCase() + words.slice(1);
	}

	let uid = 0;
	const nextID = () => "f" + ++uid;

	// --- serializing: drop empty values, keep the stored field order ---

	function clean(v, f) {
		if (f.type === "object") {
			if (f.list) {
				const items = (Array.isArray(v) ? v : []).map((x) => cleanObject(x, f.fields)).filter((x) => x);
				return items.length ? items : undefined;
			}
			return cleanObject(v, f.fields);
		}
		if (f.list) {
			const items = (Array.isArray(v) ? v : []).filter((x) => x !== "" && x != null);
			return items.length ? items : undefined;
		}
		if (v === "" || v == null || v === false) return undefined;
		return v;
	}

	function cleanObject(o, fields) {
		if (!o || typeof o !== "object") return undefined;
		const out = {};
		for (const f of fields) {
			const v = clean(o[f.field], f);
			if (v !== undefined) out[f.field] = v;
		}
		for (const k of Object.keys(o)) {
			// Keep unknown fields so the server can report them.
			if (!fields.some((f) => f.field === k) && o[k] !== undefined) out[k] = o[k];
		}
		return Object.keys(out).length ? out : undefined;
	}

	function sync() {
		ta.value = JSON.stringify(cleanObject(obj, D.fields) || {}, null, "\t");
		setStatus("");
	}

	function setStatus(text, bad) {
		if (!status) return;
		status.textContent = text;
		status.className = "small" + (bad ? " bad-text" : "");
	}

	// --- controls ---

	function refOptions(f, current) {
		const opts = D.elements.filter((e) => !f.refersTo || f.refersTo.length === 0 || f.refersTo.includes(e.kind));
		const label = (e) => (e.name ? `${e.id} — ${e.name}` : e.id) + (f.refersTo && f.refersTo.length === 1 ? "" : ` (${e.kind})`);
		const out = opts.map((e) => ({ value: e.id, label: label(e) }));
		if (current && !opts.some((e) => e.id === current)) out.push({ value: current, label: `${current} (not found)` });
		return out;
	}

	function select(id, options, value, onchange, placeholder) {
		const s = h("select", { id, onchange: () => onchange(s.value) },
			h("option", { value: "" }, placeholder || "—"),
			options.map((o) => h("option", { value: o.value, selected: o.value === value }, o.label)));
		if (value && !options.some((o) => o.value === value)) {
			s.append(h("option", { value, selected: true }, `${value} (not allowed)`));
		}
		return s;
	}

	function control(f, box, id) {
		const v = box[f.field];
		const set = (x) => {
			box[f.field] = x;
			sync();
		};

		if (f.type === "concept" || f.values) {
			const opts = (f.values || []).map((x) => ({ value: x, label: x }));
			if (!f.list) return select(id, opts, v || "", set);
			const chosen = new Set(Array.isArray(v) ? v : []);
			return h("div", { class: "checks", id }, opts.map((o) =>
				h("label", {},
					h("input", {
						type: "checkbox", checked: chosen.has(o.value),
						onchange: (ev) => {
							ev.target.checked ? chosen.add(o.value) : chosen.delete(o.value);
							if (D.kind === "Requirement" && f.field === "concerns" && box === obj) {
								if (!ev.target.checked && CONCERN_GROUPS.includes(o.value)) delete obj[o.value];
								set((f.values || []).filter((x) => chosen.has(x)));
								render(); // show or hide the safety and security groups
								return;
							}
							set((f.values || []).filter((x) => chosen.has(x)));
						},
					}),
					" " + o.label)));
		}

		if (f.type === "element ID") {
			if (!f.list) return select(id, refOptions(f, v), v || "", set);
			return chips(f, Array.isArray(v) ? v.slice() : [], set, id);
		}

		if (f.type === "boolean") {
			return h("input", { type: "checkbox", id, checked: !!v, onchange: (ev) => set(ev.target.checked) });
		}

		if (f.type === "number") {
			return h("input", {
				type: "number", step: "any", id, value: typeof v === "number" ? String(v) : "",
				oninput: (ev) => set(ev.target.value === "" ? undefined : Number(ev.target.value)),
			});
		}

		if (f.type === "date-time") {
			// Stored as UTC (RFC 3339); shown as UTC.
			const shown = typeof v === "string" ? v.slice(0, 16) : "";
			return h("span", { class: "inline" },
				h("input", {
					type: "datetime-local", id, value: shown,
					onchange: (ev) => set(ev.target.value ? ev.target.value + ":00Z" : undefined),
				}),
				h("span", { class: "muted small" }, " UTC"));
		}

		if (f.list) { // list of strings: one per line
			return h("textarea", {
				id, rows: 2, oninput: (ev) => set(ev.target.value.split("\n").map((x) => x.trim()).filter((x) => x)),
			}, Array.isArray(v) ? v.join("\n") : "");
		}

		if (f.multiline) {
			return h("textarea", { id, rows: 3, oninput: (ev) => set(ev.target.value) }, typeof v === "string" ? v : "");
		}

		const input = h("input", { type: "text", id, value: typeof v === "string" ? v : "", oninput: (ev) => set(ev.target.value) });
		if (f.field === "id" && !D.isNew && box === obj) {
			input.readOnly = true;
			input.title = "An ID can't change. Create a new element instead.";
		}
		if (f.field === "id") input.setAttribute("pattern", "[A-Za-z][A-Za-z0-9\\-]*");
		return input;
	}

	// chips shows a list of references with remove buttons and a picker to add.
	function chips(f, list, set, id) {
		const wrap = h("div", { class: "chips" });
		const draw = () => {
			wrap.replaceChildren(
				...list.map((ref, i) => {
					const e = D.elements.find((x) => x.id === ref);
					return h("span", { class: "chip" + (e ? "" : " missing"), title: e && e.name ? e.name : "" },
						h("a", { href: "/e/" + encodeURIComponent(ref), target: "_blank" }, ref),
						e && e.name ? h("span", { class: "muted" }, " " + e.name) : null,
						h("button", {
							type: "button", class: "x", "aria-label": `Remove ${ref}`,
							onclick: () => { list.splice(i, 1); set(list.slice()); draw(); },
						}, "×"));
				}),
				select(id, refOptions(f).filter((o) => !list.includes(o.value)), "", (val) => {
					if (val) { list.push(val); set(list.slice()); draw(); }
				}, "Add…"));
		};
		draw();
		return wrap;
	}

	// --- rows ---

	function row(f, box) {
		const id = nextID();
		const label = h("label", { for: id }, title(f.field), f.required ? h("span", { class: "req", title: "required" }, " *") : null);
		const helpText = f.help ? h("p", { class: "help-text" }, f.help) : null;

		if (f.type === "object" && f.list) {
			if (!Array.isArray(box[f.field])) box[f.field] = [];
			const items = box[f.field];
			const list = h("div", { class: "items" });
			const draw = () => {
				list.replaceChildren(...items.map((item, i) =>
					h("fieldset", { class: "item" },
						h("legend", {}, `${title(one(f.field))} ${i + 1}`),
						f.fields.map((sf) => row(sf, item)),
						h("button", {
							type: "button", class: "quiet small-button",
							onclick: () => { items.splice(i, 1); sync(); draw(); },
						}, "Remove"))));
			};
			draw();
			return h("div", { class: "field" }, h("span", { class: "label" }, title(f.field)), helpText, list,
				h("button", {
					type: "button", class: "quiet small-button",
					onclick: () => { items.push({}); draw(); },
				}, `+ Add ${one(f.field)}`));
		}

		if (f.type === "object") {
			if (!box[f.field] || typeof box[f.field] !== "object") box[f.field] = {};
			const sub = box[f.field];
			return h("fieldset", { class: "group" }, h("legend", {}, title(f.field)), helpText, f.fields.map((sf) => row(sf, sub)));
		}

		return h("div", { class: "field" }, label, control(f, box, id), helpText);
	}

	function shown(f) {
		if (D.kind !== "Requirement" || !CONCERN_GROUPS.includes(f.field)) return true;
		const concerns = Array.isArray(obj.concerns) ? obj.concerns : [];
		return concerns.includes(f.field) || clean(obj[f.field], f) !== undefined;
	}

	function render() {
		const top = D.fields.filter((f) => !LATER.includes(f.field) && shown(f));
		const later = D.fields.filter((f) => LATER.includes(f.field));
		const more = h("details", { class: "more" },
			h("summary", {}, "More: " + later.map((f) => title(f.field).toLowerCase()).join(", ")),
			later.map((f) => row(f, obj)));
		if (later.some((f) => clean(obj[f.field], f) !== undefined)) more.open = true;
		root.replaceChildren(...top.map((f) => row(f, obj)), more);
	}

	// JSON edits update the form once they parse.
	let timer;
	ta.addEventListener("input", () => {
		clearTimeout(timer);
		timer = setTimeout(() => {
			const v = parse(ta.value);
			if (!v) {
				setStatus("The JSON has an error, so the form shows the last valid version.", true);
				return;
			}
			obj = v;
			render();
			setStatus("");
		}, 400);
	});

	render();
	if (D.isNew) sync(); // show the clean starting point
})();
